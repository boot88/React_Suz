#!/usr/bin/env bash
# Точка входа для ярлыка на рабочем столе: перенос проверенной версии из
# React_Suz_dev на боевой сервер hund03 (192.168.129.31).
#
#   bash tools/deploy-to-hund03-button.sh          — предпросмотр, вопрос, перенос
#   DRY_RUN=1 bash tools/deploy-to-hund03.sh       — только список изменений
#
# Порядок работы:
#   1) показывает, какие файлы изменятся (сухой прогон, ничего не переносится);
#   2) спрашивает подтверждение;
#   3) запускает штатный tools/deploy-to-hund03.sh: копия боевой папки,
#      перенос кода, сборка клиента на сервере, перезапуск службы react-suz.
#
# НЕ ЗАТРАГИВАЮТСЯ: база MySQL (дампы и восстановление не выполняются), боевой .env
# (пароль MySQL, секрет токенов), server/data (JSON-хранилища и архивы),
# server/uploads (аватары и файлы чатов). Подробности — в tools/deploy-to-hund03.sh.
set -uo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$DEV_DIR"

REMOTE="${REMOTE:-qwest@192.168.129.31}"

printf '\033[1;36m== Предпросмотр: что будет перенесено на %s ==\033[0m\n' "$REMOTE"
if ! DRY_RUN=1 bash tools/deploy-to-hund03.sh; then
  echo
  echo "❌ Предпросмотр не удался (нет связи с сервером?). Перенос отменён, ничего не изменено."
  exit 1
fi

echo
echo "Файлы с «+++++++++» — новые, с «.st......» — обновлённые (t — время, s — размер)."
read -r -p "Перенести это на боевой сервер и перезапустить службу react-suz? (y/N) " answer
case "${answer:-}" in
  [yYдД]*) ;;
  *) echo "Отменено. Боевая версия не изменена."; exit 0 ;;
esac

bash tools/deploy-to-hund03.sh
